#!/usr/bin/env python3
"""
Generate thesis table step3_stats_tests.tex from statistical tests.
Uses baselines NB=2 and NB=3, Holm correction, for Step Length = 100.
Run from repo root or from experiments/: python experiments/generate_step3_stats_table.py
"""
from pathlib import Path
import re
import sys

# Allow running as script from experiments/ or from repo root
if __name__ == "__main__":
    repo_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(repo_root))
    sys.path.insert(0, str(Path(__file__).resolve().parent))

from analyze_neighborhood_sizes import NeighborhoodSizeAnalyzer


def _sig_nbs_from_posthoc(posthoc, model, metric):
    """Extract sorted list of significant NB_other from posthoc rows for (model, metric)."""
    ph = posthoc[(posthoc["Model Type"] == model) & (posthoc["Metric"] == metric)]
    if "NB_other" in ph.columns:
        return sorted(ph[ph["Significant"]]["NB_other"].astype(int).tolist())
    sig_nbs = []
    for _, r in ph[ph["Significant"]].iterrows():
        t = r["Test"]
        m = re.search(r"NB(\d+)", t)
        if m:
            sig_nbs.append(int(m.group(1)))
    return sorted(set(sig_nbs))


def main():
    repo_root = Path(__file__).resolve().parent.parent
    experiments_dir = Path(__file__).resolve().parent
    results_dir = experiments_dir / "results_extended" / "tissue_simulation_nb_sweep_300x100"
    if not results_dir.exists():
        print(f"Results dir not found: {results_dir}")
        sys.exit(1)

    histories_path = repo_root / "histories.npy"
    if not histories_path.exists():
        histories_path = experiments_dir / "dummy_histories.npy"
        if not histories_path.exists():
            import numpy as np
            np.save(histories_path, np.zeros((1, 2, 35, 35), dtype=np.float32))
            print(f"Created dummy {histories_path} for analyzer init")

    analyzer = NeighborhoodSizeAnalyzer(
        results_dir=str(results_dir),
        histories_path=str(histories_path),
        device="cpu",
        n_evaluations=1,
        step_lengths=[100],
        experiment_subdir=None,
    )
    analyzer.base_dir = Path(results_dir)

    baselines = [2, 3]
    results_per_baseline = {}

    for bl in baselines:
        print(f"Running statistical tests (Step Length=100, baseline NB={bl}, Holm correction)...")
        df = analyzer.statistical_significance_tests(
            alpha=0.05,
            correction_method="holm",
            include_effect_size=False,
            step_length_filter=100,
            baseline_nb=bl,
        )
        if df.empty:
            print("No results.")
            sys.exit(1)
        results_per_baseline[bl] = df

    kw = results_per_baseline[2][results_per_baseline[2]["Test"] == "Kruskal-Wallis"]

    def format_p(p):
        if p < 1e-4:
            return "$<10^{-4}$"
        return f"${p:.4f}$"

    rows = []
    for _, row in kw.iterrows():
        model = row["Model Type"]
        metric = row["Metric"]
        p_kw = row["p_value"]
        posthoc2 = results_per_baseline[2][results_per_baseline[2]["Test"] != "Kruskal-Wallis"]
        posthoc3 = results_per_baseline[3][results_per_baseline[3]["Test"] != "Kruskal-Wallis"]
        sig2 = _sig_nbs_from_posthoc(posthoc2, model, metric)
        sig3 = _sig_nbs_from_posthoc(posthoc3, model, metric)
        sig_str_2 = ",".join(str(n) for n in sig2) if sig2 else "---"
        sig_str_3 = ",".join(str(n) for n in sig3) if sig3 else "---"
        rows.append((model, metric, format_p(p_kw), sig_str_2, sig_str_3))

    out_path = repo_root / "thesis-latex" / "tables" / "step3_stats_tests.tex"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    with open(out_path, "w") as f:
        f.write("% Auto-generated by experiments/generate_step3_stats_table.py\n")
        f.write("% Statistical tests: Step Length=100, baselines NB=2 and NB=3, Holm correction.\n")
        f.write("\\begin{table}[H]\n")
        f.write("\\centering\n")
        f.write("\\small\n")
        f.write("\\begin{tabulary}{\\textwidth}{lLrLL}\n")
        f.write("\\toprule\n")
        f.write("Model & Metric & Kruskal--Wallis $p$ & Significant vs NB=2 & Significant vs NB=3 \\\\\n")
        f.write("\\midrule\n")
        for model, metric, p_str, s2, s3 in rows:
            model_esc = model.replace(" ", "~")
            f.write(f"{model_esc} & {metric} & {p_str} & {s2} & {s3} \\\\\n")
        f.write("\\bottomrule\n")
        f.write("\\end{tabulary}\n")
        f.write("\\caption{Non-parametric statistical tests across neighborhood sizes for Step Length $=100$. ")
        f.write("We report Kruskal--Wallis across $NB\\in\\{1,\\dots,7\\}$ and post-hoc Mann--Whitney U with Holm correction: ")
        f.write("each $NB>2$ is compared to the baseline $NB=2$, and each $NB>3$ to the baseline $NB=3$. ")
        f.write("Columns list which neighborhood sizes differ significantly from each baseline.}\n")
        f.write("\\label{tab:impl:step3:stats}\n")
        f.write("\\end{table}\n")

    print(f"Wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
